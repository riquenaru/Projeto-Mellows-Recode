CREATE TABLE books (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(180) NOT NULL,
    author VARCHAR(180) NOT NULL,
    summary VARCHAR(1200) NOT NULL,
    category VARCHAR(80) NOT NULL,
    reading_level VARCHAR(24) NOT NULL CHECK (reading_level IN ('INICIANTE', 'INTERMEDIARIO', 'AVANCADO')),
    cover_image VARCHAR(300) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_books_active_title ON books (active, title);
CREATE INDEX idx_books_reading_level ON books (reading_level);

CREATE TABLE community_signups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(254) NOT NULL,
    consent BOOLEAN NOT NULL CHECK (consent = TRUE),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_community_signups_email UNIQUE (email)
);

CREATE TABLE exchange_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id BIGINT NOT NULL REFERENCES books (id),
    name VARCHAR(100) NOT NULL,
    email VARCHAR(254) NOT NULL,
    message VARCHAR(1000),
    status VARCHAR(24) NOT NULL DEFAULT 'RECEIVED' CHECK (status IN ('RECEIVED', 'IN_REVIEW', 'CLOSED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_exchange_requests_book ON exchange_requests (book_id);
CREATE INDEX idx_exchange_requests_status_created ON exchange_requests (status, created_at DESC);

